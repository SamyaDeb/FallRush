// Generates the Unity-side constants for modifiers_v1.json (M3; the movement_v1 pattern).
// Output: client-unity/Assets/_Game/Scripts/Shared/ModifiersData.g.cs
// An EditMode test re-serialises the typed values to canonical JSON and checks the hash, hashes the JSON file on disk,
// and checks the ids/keys against map_pool_v1.json.
// Usage: pnpm gen:modifiers   (then `pnpm hash` prints the same sha256)
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { canonicalize, loadConfigJson, sha256, MODIFIERS_V1_FILE, MAP_POOL_V1_FILE } from "../src/canonical";

type Mod = Record<string, number | string>;
const json = loadConfigJson(MODIFIERS_V1_FILE) as { version: number; name: string; mapPool: string; units: string; notes: string; modifiers: Mod[] };
const pool = loadConfigJson(MAP_POOL_V1_FILE) as { modifiers: { id: number; key: string }[] };
const canon = canonicalize(json);
const hash = sha256(canon).toString("hex");

const fields = ["fogPermille", "fovDeltaDeg", "gravityPermille", "groundDecelPermille", "hazardSpeedPermille", "id", "jumpApexPermille", "key", "knockbackPermille", "scope", "telegraphPermille"];
if (json.modifiers.length !== pool.modifiers.length) throw new Error("modifier count differs from map_pool_v1.json");
json.modifiers.forEach((m, i) => {
  const keys = Object.keys(m).sort();
  if (JSON.stringify(keys) !== JSON.stringify(fields)) throw new Error(`modifier ${i}: fields ${keys}`);
  if (m.id !== pool.modifiers[i].id || m.key !== pool.modifiers[i].key) throw new Error(`modifier ${i}: id/key differ from map_pool_v1.json`);
});

const rows = json.modifiers
  .map((m) => `            new ModifierEffects(${m.id}, ${JSON.stringify(m.key)}, ${JSON.stringify(m.scope)}, ${m.gravityPermille}, ${m.jumpApexPermille}, ${m.groundDecelPermille}, ${m.hazardSpeedPermille}, ${m.telegraphPermille}, ${m.knockbackPermille}, ${m.fovDeltaDeg}, ${m.fogPermille}),`)
  .join("\n");

const out = `// <auto-generated>
// Generated by packages/shared/scripts/gen-modifiers-cs.ts from packages/shared/config/${MODIFIERS_V1_FILE}.
// Do not edit by hand: edit the JSON, then run \`pnpm gen:modifiers\`.
// </auto-generated>
namespace FallRush.Shared
{
    public static class ModifiersData
    {
        public const string File = ${JSON.stringify(MODIFIERS_V1_FILE)};
        public const string Sha256Hex = ${JSON.stringify(hash)};
        public const string CanonicalJson = ${JSON.stringify(canon)};
        public const int Version = ${json.version};
        public const string Name = ${JSON.stringify(json.name)};
        public const string MapPool = ${JSON.stringify(json.mapPool)};
        public const string Units = ${JSON.stringify(json.units)};
        public const string Notes = ${JSON.stringify(json.notes)};

        public static readonly ModifierEffects[] All =
        {
${rows}
        };
    }
}
`;
const path = join(__dirname, "..", "..", "..", "client-unity", "Assets", "_Game", "Scripts", "Shared", "ModifiersData.g.cs");
writeFileSync(path, out);
console.log(`wrote ${path}\n${MODIFIERS_V1_FILE} sha256=${hash} bytes=${Buffer.byteLength(canon)}`);
