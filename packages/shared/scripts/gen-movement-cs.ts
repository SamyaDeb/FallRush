// Generates the Unity-side constants for the movement config the game uses (movement_v3.json since G4.1c = v2 + the bump flag; v1/v2 kept for history) (doc 04 §5, M2).
// Output: client-unity/Assets/_Game/Scripts/Shared/MovementConfigData.g.cs
// The C# file embeds the canonical JSON + its sha256 and one const per leaf value. An EditMode test
// re-serialises the typed constants to canonical JSON and checks the hash, and also hashes the JSON file on disk.
// Usage: pnpm gen:movement   (then `pnpm hash` prints the same sha256)
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { canonicalize, loadConfigJson, sha256, MOVEMENT_V3_FILE } from "../src/canonical";

const json = loadConfigJson(MOVEMENT_V3_FILE) as Record<string, unknown>;
const canon = canonicalize(json);
const hash = sha256(canon).toString("hex");

const pascal = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const lines: string[] = [];
function walk(obj: Record<string, unknown>, prefix: string[]) {
  for (const key of Object.keys(obj).sort()) {
    const v = obj[key];
    const name = [...prefix, pascal(key)].join("_");
    if (typeof v === "number") {
      if (!Number.isSafeInteger(v) || v > 2147483647 || v < -2147483648) throw new Error(`${name}: not an int32`);
      lines.push(`        public const int ${name} = ${v};`);
    } else if (typeof v === "boolean") {
      lines.push(`        public const bool ${name} = ${v ? "true" : "false"};`);
    } else if (typeof v === "string") {
      lines.push(`        public const string ${name} = ${JSON.stringify(v)};`);
    } else if (v && typeof v === "object" && !Array.isArray(v)) {
      walk(v as Record<string, unknown>, [...prefix, pascal(key)]);
    } else {
      throw new Error(`${name}: unsupported value type`);
    }
  }
}
walk(json, []);

const out = `// <auto-generated>
// Generated by packages/shared/scripts/gen-movement-cs.ts from packages/shared/config/${MOVEMENT_V3_FILE}.
// Do not edit by hand: edit the JSON, then run \`pnpm gen:movement\`.
// </auto-generated>
namespace FallRush.Shared
{
    public static class MovementConfigData
    {
        public const string File = ${JSON.stringify(MOVEMENT_V3_FILE)};
        public const string Sha256Hex = ${JSON.stringify(hash)};
        public const string CanonicalJson = ${JSON.stringify(canon)};

${lines.join("\n")}
    }
}
`;
const path = join(__dirname, "..", "..", "..", "client-unity", "Assets", "_Game", "Scripts", "Shared", "MovementConfigData.g.cs");
writeFileSync(path, out);
console.log(`wrote ${path}\n${MOVEMENT_V3_FILE} sha256=${hash} bytes=${Buffer.byteLength(canon)}`);
