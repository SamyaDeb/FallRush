/// <summary>
/// Writes the hazard determinism vectors (M3 §3.4): <c>Tests/Vectors/hazard_vectors_v1.json</c> and the generated
/// <c>Scripts/Shared/Hazards/HazardVectorsExpected.g.cs</c> (the same numbers, so player builds can self-test).
/// Run only when a hazard function changes on purpose; the EditMode test and the self-tests compare against these.
/// Batch: <c>bash scripts/m1-unity.sh vectors -executeMethod HazardVectorsTool.Generate</c>.
/// </summary>
public static class HazardVectorsTool
{
    public const string JsonPath = ProjectSetup.Root + "/Tests/Vectors/hazard_vectors_v1.json";
    public const string CsPath = ProjectSetup.Root + "/Scripts/Shared/Hazards/HazardVectorsExpected.g.cs";

    [MenuItem("Fall Rush/Tests/Regenerate hazard vectors")]
    public static void Generate()
    {
        var all = HazardVectors.ComputeAll();
        var digest = HazardVectors.Digest(all);
        var platform = $"{SystemInfo.operatingSystem} / {SystemInfo.processorType} / Unity {Application.unityVersion} Editor (Mono)";

        var js = new StringBuilder(200000);
        js.Append("{\n \"version\": ").Append(HazardVectors.Version).Append(",\n \"count\": ").Append(HazardVectors.Count)
            .Append(",\n \"width\": ").Append(HazardVectors.Width).Append(",\n \"digest\": \"").Append(digest).Append("\",\n \"generatedOn\": \"")
            .Append(platform.Replace("\"", "'")).Append("\",\n \"fields\": [");
        for (var f = 0; f < HazardVectors.Fields.Length; f++)
            js.Append(f > 0 ? ", " : "").Append('"').Append(HazardVectors.Fields[f]).Append('"');
        js.Append("],\n \"cases\": [\n");
        for (var i = 0; i < HazardVectors.Count; i++)
        {
            js.Append("  [");
            for (var f = 0; f < HazardVectors.Width; f++)
                js.Append(f > 0 ? "," : "").Append(all[i * HazardVectors.Width + f]);
            js.Append(i < HazardVectors.Count - 1 ? "],\n" : "]\n");
        }

        js.Append(" ]\n}\n");
        Directory.CreateDirectory(Path.GetDirectoryName(JsonPath));
        File.WriteAllText(JsonPath, js.ToString());

        var cs = new StringBuilder(200000);
        cs.Append("// <auto-generated>\n// Generated by Editor/HazardVectorsTool.cs (same numbers as Tests/Vectors/hazard_vectors_v1.json).\n// Do not edit by hand.\n// </auto-generated>\n");
        cs.Append("namespace FallRush.Shared\n{\n    public static class HazardVectorsExpected\n    {\n");
        cs.Append("        public const string Digest = \"").Append(digest).Append("\";\n");
        cs.Append("        public const string GeneratedOn = \"").Append(platform.Replace("\"", "'")).Append("\";\n");
        cs.Append("        public static readonly int[] Data =\n        {\n");
        for (var i = 0; i < HazardVectors.Count; i++)
        {
            cs.Append("            ");
            for (var f = 0; f < HazardVectors.Width; f++)
                cs.Append(all[i * HazardVectors.Width + f]).Append(", ");
            cs.Append('\n');
        }

        cs.Append("        };\n    }\n}\n");
        File.WriteAllText(CsPath, cs.ToString());
        AssetDatabase.Refresh();
        Debug.Log($"[setup] hazard vectors: {HazardVectors.Count} cases, digest {digest} → {JsonPath}, {CsPath}");
    }

