#!/usr/bin/env bash
# G1 map QA (doc 08 §9, M4 §5.2): every new map × variant × allowed modifier × N runs with BotBrain bots (reference and
# normal tiers), plus Block Party Dash with BotBrain normal. Mac dev server, headless, no networking.
# usage: scripts/g1-qa.sh [runs=100] [maps...]   → .m1-logs/g1/qa-<map>.md, combined into docs/proof/g1-map-qa.md
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BIN="$(ls "$ROOT/client-unity/Builds/MacDevServer/FallRushDevServer.app/Contents/MacOS/"* | head -1)"
RUNS="${1:-100}"; shift || true
MAPS=("$@"); [[ ${#MAPS[@]} -gt 0 ]] || MAPS=(GooTower StarScramble CrumbleShelf BlockPartyDash)
OUT="$ROOT/.m1-logs/g1"; mkdir -p "$OUT"
for m in "${MAPS[@]}"; do
  tier=both; [[ "$m" == "BlockPartyDash" ]] && tier=normal
  start=$(date +%s)
  "$BIN" -batchmode -nographics -fallrushQA "$RUNS" -fallrushQATier "$tier" -fallrushMap "$m" -fallrushQAOut "$OUT/qa-$m.md" -logFile "$OUT/qa-$m.log" > /dev/null 2>&1 || true
  echo "[g1-qa] $m: $(grep -o 'QA [A-Z]*' "$OUT/qa-$m.md" | tail -1) in $(( $(date +%s) - start )) s"
done
{
  echo "# G1 map QA (generated by scripts/g1-qa.sh, $(date -u +%Y-%m-%dT%H:%MZ), Mac dev server, $RUNS runs per cell)"
  echo
  for m in "${MAPS[@]}"; do cat "$OUT/qa-$m.md"; echo; done
} > "$ROOT/docs/proof/g1-map-qa.md"
echo "[g1-qa] → docs/proof/g1-map-qa.md"
