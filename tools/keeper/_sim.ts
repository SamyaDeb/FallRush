import { Transaction } from "@solana/web3.js";
import { er, pe, pda, wallet, tickAccounts, cu, decodeWorld } from "./lib.ts";
const arena = pda.arena(0);
const a: any = await pe.account.arena.fetch(arena);
const metas = tickAccounts(arena, a.matchAccount, a.maps);
const w = decodeWorld((await er.getAccountInfo(pda.world(arena)))!.data as Buffer);
console.log("world tick", w.tick, "part", w.partPending, "lastCode", w.lastCode, "execs", w.executions, "notdue", w.notDue);
const tx = new Transaction().add(cu(1_400_000), await pe.methods.tick().remainingAccounts(metas).instruction());
tx.feePayer = wallet.publicKey; tx.recentBlockhash = (await er.getLatestBlockhash()).blockhash; tx.sign(wallet);
const r = await er.simulateTransaction(tx);
console.log("err", JSON.stringify(r.value.err), "units", r.value.unitsConsumed); console.log((r.value.logs ?? []).slice(-6).join("\n"));
process.exit(0);
