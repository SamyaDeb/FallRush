//! Writes the 1,024-entry Q15 sine table for rush-core (P1 prompt B.2).
//! Entry i = round_half_away(sin(2π·i/1024) · 32768), i = 0..=1024 (the last entry repeats entry 0 so
//! interpolation never wraps). Floats are allowed here only; rush-core asserts the sha256 of the emitted file.
use std::fmt::Write as _;

fn main() {
    let out = std::env::args().nth(1).unwrap_or_else(|| "crates/rush-core/src/fx/trig_table.rs".into());
    let mut s = String::new();
    s.push_str("// @generated by tools/gen-trig (do not edit). sin(2*pi*i/1024) * 32768, rounded half away from zero.\n");
    s.push_str("// Its sha256 is asserted in rush-core's tests (fx::tests::trig_table_hash).\n");
    s.push_str("/// Full-turn Q15 sine table, 1,025 entries (entry 1024 = entry 0).\n");
    s.push_str("pub const SIN_Q15: [i32; 1025] = [\n");
    for i in 0..=1024usize {
        let v = (2.0 * std::f64::consts::PI * (i % 1024) as f64 / 1024.0).sin() * 32768.0;
        let r = if v >= 0.0 { (v + 0.5).floor() } else { -((-v + 0.5).floor()) };
        if i % 16 == 0 {
            s.push_str("   ");
        }
        write!(s, " {},", r as i64).unwrap();
        if i % 16 == 15 || i == 1024 {
            s.push('\n');
        }
    }
    s.push_str("];\n");
    std::fs::write(&out, s).expect("write table");
    eprintln!("wrote {out}");
}
